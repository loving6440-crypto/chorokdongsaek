export const EMPTY_SCRIPT = '(스크립트 준비 중)'

/** (하위 호환) 문구 목록 → 보여 줄 문단들 */
export const resolveEntries = (entries = [], stats = {}, seed = '', now = Date.now(), rng = Math.random) => resolveSceneEntries(entries, stats, seed, now, rng)

const nodeOf = (floorId, id) => {
  const floor = FLOORS.find((f) => f.id === floorId)
  const walk = (list = []) => {
    for (const n of list) {
      if (n.id === id) return n
      const f = walk(n.choices ?? [])
      if (f) return f
    }
    return null
  }
  return walk(floor?.areas)
}

/** 구역(또는 선택지)의 그날 글. 문단 배열. 비어 있으면 '준비 중' 문구 한 줄. */
export function scriptOfDay(floorId, id, now = Date.now(), stats = {}) {
  const paras = resolveEntries(nodeOf(floorId, id)?.text ?? [], stats, `mainHall:${floorId}|${id}`, now, () => 1)
  return paras.length ? paras : [EMPTY_SCRIPT]
}

/** 층 둘러보기 문구 */
export function introOf(floor, now = Date.now(), stats = {}) {
  return resolveEntries(floor.intro ?? [], stats, `${floor.id}|intro`, now, () => 1)
}
