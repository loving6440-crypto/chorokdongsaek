/** 문자열 → 32비트 해시 (FNV-1a) */
function hashString(str) {
  let h = 0x811c9dc5
  for (let i = 0; i < str.length; i++) {
    h ^= str.charCodeAt(i)
    h = Math.imul(h, 0x01000193)
  }
  return h >>> 0
}

/** 같은 시드면 같은 수열을 내는 난수 (mulberry32) */
export function seededRandom(seed) {
  let a = seed >>> 0
  return () => {
    a = (a + 0x6d2b79f5) >>> 0
    let t = a
    t = Math.imul(t ^ (t >>> 15), t | 1)
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61)
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

export function todayKey(date = new Date()) {
  const p = (n) => String(n).padStart(2, '0')
  return `${date.getFullYear()}-${p(date.getMonth() + 1)}-${p(date.getDate())}`
}

export function pickRank(rand) {
  const total = RANKS.reduce((sum, r) => sum + r.weight, 0)
  let roll = rand() * total
  for (const r of RANKS) {
    roll -= r.weight
    if (roll < 0) return r
  }
  return RANKS[RANKS.length - 1]
}

const pick = (list, rand) => list[Math.floor(rand() * list.length)]

/** 시드로 하루치 운세를 만든다. forceRank(id) 를 주면 등급을 고정한다. (테스트용) */
export function drawFortune(seedText, forceRank) {
  const rand = seededRandom(hashString(seedText))
  const rank = (forceRank && RANKS.find((r) => r.id === forceRank)) || pickRank(rand)
  const book = PHRASES[rank.id]
  return {
    rankId: rank.id,
    summary: pick(book.summary, rand),
    sections: [
      { label: '수업운', text: pick(book.study, rand) },
      { label: '수련운', text: pick(book.training, rand) },
      { label: '인연운', text: pick(book.bond, rand) },
      { label: '오늘의 조언', text: pick(book.advice, rand) },
    ],
    lucky: [
      { label: '행운의 색', text: pick(LUCKY.colors, rand) },
      { label: '행운의 방위', text: pick(LUCKY.directions, rand) },
      { label: '행운의 숫자', text: String(1 + Math.floor(rand() * 9)) },
      { label: '행운의 물건', text: pick(LUCKY.items, rand) },
      { label: '길한 시간', text: pick(LUCKY.hours, rand) },
    ],
  }
}
