export const EMPTY_SCRIPT = '(스크립트 준비 중)'

const hash = (str) => {
  let h = 2166136261
  for (let i = 0; i < str.length; i++) h = Math.imul(h ^ str.charCodeAt(i), 16777619)
  return h >>> 0
}

const meets = (when, stats = {}) =>
  Object.entries(when ?? {}).every(([k, [lo, hi]]) => (lo == null || (stats[k] ?? 0) >= lo) && (hi == null || (stats[k] ?? 0) <= hi))

/**
 * 문구 목록 → 보여 줄 문단들. 기본 문구는 같은 날엔 같은 것, 날이 바뀌면 다른 것이 나올 수 있다.
 * 조건 문구는 지금 스탯이 조건을 채울 때만 붙는다(replace 는 기본 문구를 대신한다).
 */
export function resolveEntries(entries = [], stats = {}, seed = '', now = Date.now()) {
  const plain = entries.filter((e) => typeof e === 'string')
  const cond = entries.filter((e) => typeof e === 'object' && meets(e.when, stats))
  const base = plain.length ? plain[hash(`${dayKey(now)}|${seed}`) % plain.length] : null
  const replace = cond.filter((c) => c.mode === 'replace').at(-1)
  const out = []
  if (replace) out.push(replace.text)
  else if (base) out.push(base)
  for (const c of cond) if (c.mode !== 'replace') out.push(c.text)
  return out
}

/** 구역(또는 세부 조사)의 그날 스크립트. 문단 배열. 비어 있으면 '준비 중' 문구 한 줄. */
export function scriptOfDay(floorId, id, now = Date.now(), stats = {}) {
  const paras = resolveEntries(SCRIPTS[floorId]?.[id] ?? [], stats, `${floorId}|${id}`, now)
  return paras.length ? paras : [EMPTY_SCRIPT]
}

/** 층 둘러보기 문구 */
export function introOf(floor, now = Date.now(), stats = {}) {
  return resolveEntries(floor.intro ?? [], stats, `${floor.id}|intro`, now)
}
