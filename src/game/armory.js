/** 방문/대화 시 선택되는 일반 대사. RNG 주입으로 테스트 가능. */
export function pickShinahLine(rng = Math.random) {
  return SHINAH.lines[Math.min(SHINAH.lines.length - 1, Math.max(0, Math.floor(rng() * SHINAH.lines.length)))].text
}

/** 선물 후 호감도에 따라 해금되는 대사 중 가장 높은 단계의 반응. */
export function shinahGiftLine(affinity) {
  return [...SHINAH.giftLines].reverse().find(line => affinity >= line.minAffinity)?.text ?? null
}
